//! The scenario catalog and its closed vocabularies — one authority for Rust runtime, manifest
//! validation and scenario lint.
//!
//! The players runtime and every validator read this module, so there is no second copy to drift.

/// One compiled scenario the players runtime implements.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ScenarioInfo {
    pub name: &'static str,
    /// Behaviour family, e.g. `group_motion`.
    pub family: &'static str,
    /// Fewest bots the script is meaningful with.
    pub min_players: u32,
    /// True when roles/peers resolve against local bot indices, so the swarm must not be sharded.
    pub single_process: bool,
    /// True when the scenario edits the world (builds, mines).
    pub world_edits: bool,
    /// Scenery generator that suits the scenario; `none` for untouched terrain.
    pub recommended_scenery: &'static str,
    /// True when the scenario requires `far_players` spectators placed at distance.
    pub needs_far_players: bool,
    /// Dataset generation the scenario was authored for. 0 = explicit-only showcase scenarios that
    /// no generator selects by default; 5 = the original scenario set; 6 = authored
    /// for loop-shaped trajectories, camera turns that come back, and compact staging on real
    /// terrain; 7 = a focused interaction / co-visibility / local-grounding set. Older generations
    /// stay compiled and unchanged so data collected from them remains reproducible.
    pub generation: u8,
}

const fn s(
    name: &'static str,
    family: &'static str,
    min_players: u32,
    single_process: bool,
    world_edits: bool,
    recommended_scenery: &'static str,
    needs_far_players: bool,
) -> ScenarioInfo {
    ScenarioInfo {
        name,
        family,
        min_players,
        single_process,
        world_edits,
        recommended_scenery,
        needs_far_players,
        generation: 5,
    }
}

