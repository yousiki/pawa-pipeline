/// Catalog lookup by name.
pub fn scenario(name: &str) -> Option<&'static ScenarioInfo> {
    SCENARIOS.iter().find(|info| info.name == name)
}

/// Scenery generators the coordinator can build. `none` means untouched terrain.
pub const KNOWN_SCENERY: &[&str] = &[
    "none",
    "build_arena",
    "combat_arena",
    "gap_jump",
    "mining_arena",
];

/// The items a script may `equip`, in the canonical form the runtime compares against.
///
/// The list is closed because `Ctx::equip` searches the hotbar and silently equips nothing when
/// the item is not there. THE SOURCE OF TRUTH is the material kit the coordinator stocks into
/// every bot's hotbar on every episode — the capture crate must keep its kit identical to this
/// list (a test in its coordinator pins that).
pub const EQUIP_ITEMS: &[&str] = &[
    "stone_bricks",
    "oak_planks",
    "oak_log",
    "cobblestone",
    "bricks",
    "stone",
    "diamond_pickaxe",
    "diamond_sword",
    "torch",
];

/// The material kit the coordinator stocks into every bot's hotbar: slot `i` holds
/// `EQUIP_ITEMS[i]`, tools as single items and everything else as a full stack.
///
/// Shared between the capture coordinator (which issues the `item replace` commands) and the
/// render driver spec (which paints the same kit into the replay HUD): the protocol never syncs a
/// spectated remote player's container, so without this the rendered hotbar shows one morphing
/// slot — the mainhand equipment folded into slot 0 — instead of the kit the bot really carries.
pub fn hotbar_kit() -> Vec<(&'static str, u32)> {
    EQUIP_ITEMS
        .iter()
        .map(|item| match *item {
            "diamond_pickaxe" | "diamond_sword" => (*item, 1),
            _ => (*item, 64),
        })
        .collect()
}

/// Canonical `pNN` naming shared by every stage: width grows with the swarm, minimum two digits.
pub fn pov_name(index: usize, total: usize) -> String {
    let width = usize::max(2, total.saturating_sub(1).to_string().len());
    format!("p{index:0width$}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalog_is_well_formed() {
        assert_eq!(SCENARIOS.len(), 195);
        assert_eq!(SCENARIOS.iter().filter(|i| i.generation == 0).count(), 1);
        assert_eq!(SCENARIOS.iter().filter(|i| i.generation == 5).count(), 70);
        assert_eq!(SCENARIOS.iter().filter(|i| i.generation == 6).count(), 112);
        assert_eq!(SCENARIOS.iter().filter(|i| i.generation == 7).count(), 12);
        assert!(
            SCENARIOS
                .iter()
                .filter(|i| i.generation == 6 && i.family != "evaluation")
                .count()
                >= 100
        );
        for info in SCENARIOS {
            assert!(
                KNOWN_SCENERY.contains(&info.recommended_scenery),
                "{}",
                info.name
            );
            assert!(info.min_players >= 1, "{}", info.name);
        }
        // Only the rendezvous scenarios place far players.
        let far: Vec<_> = SCENARIOS
            .iter()
            .filter(|i| i.needs_far_players)
            .map(|i| i.name)
            .collect();
        assert_eq!(far, ["cross_region_rendezvous", "rendezvous_after_edits"]);
    }

    #[test]
    fn naming_width_is_stable() {
        assert_eq!(pov_name(0, 1), "p00");
        assert_eq!(pov_name(7, 50), "p07");
        assert_eq!(pov_name(100, 101), "p100");
    }
}
